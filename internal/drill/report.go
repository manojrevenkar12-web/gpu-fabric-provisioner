package drill

import (
	"fmt"
	"strings"
)

// Markdown renders results as the drill report.
func Markdown(results []*Result) string {
	var b strings.Builder
	b.WriteString("# Drill results\n\n")
	b.WriteString("Generated by `go run ./cmd/drill`. Every run uses a fresh kube-apiserver and etcd (envtest), the simulated\n")
	b.WriteString("cloud, kubelets and scheduler in `internal/sim`, and the same workload for both provisioners. GPU-seconds\n")
	b.WriteString("are counted from the cloud's instances (paid) and from running pods (useful) until the last job finished.\n")
	b.WriteString("Timings are compressed: servers boot in 1.5–3 s and advertise GPUs 2 s after registering.\n")
	fmt.Fprintf(&b, "A gang whose members land in different fabrics is assumed to run %.0f× slower (its collectives leave InfiniBand);\n", SplitSlowdown)
	b.WriteString("its GPU time is not counted as useful.\n\n")
	byScenario := map[string][]*Result{}
	var order []string
	for _, r := range results {
		if _, ok := byScenario[r.Scenario]; !ok {
			order = append(order, r.Scenario)
		}
		byScenario[r.Scenario] = append(byScenario[r.Scenario], r)
	}
	summaries := map[string]string{}
	for _, sc := range Scenarios() {
		summaries[sc.Name] = sc.Summary
	}
	for _, name := range order {
		rs := byScenario[name]
		fmt.Fprintf(&b, "## %s\n\n%s.\n\n", name, capitalize(summaries[name]))
		b.WriteString("| | " + strings.Join(modes(rs), " | ") + " |\n|---|" + strings.Repeat("---|", len(rs)) + "\n")
		row := func(label string, f func(*Result) string) {
			cells := make([]string, len(rs))
			for i, r := range rs {
				cells[i] = f(r)
			}
			fmt.Fprintf(&b, "| %s | %s |\n", label, strings.Join(cells, " | "))
		}
		row("Jobs completed", func(r *Result) string {
			s := fmt.Sprintf("%d / %d", r.Completed, r.Jobs)
			if r.TimedOut {
				s += " (timed out)"
			}
			return s
		})
		row("Gangs split across fabrics", func(r *Result) string { return fmt.Sprint(r.SplitGangs) })
		row("Gang restarts", func(r *Result) string { return fmt.Sprint(r.GangRestarts) })
		row("Gang wait p50 / p95", func(r *Result) string {
			return fmt.Sprintf("%.1f s / %.1f s", r.GangWaitP50Seconds, r.GangWaitP95Seconds)
		})
		row("Makespan", func(r *Result) string { return fmt.Sprintf("%.1f s", r.MakespanSeconds) })
		row("Servers created (peak)", func(r *Result) string { return fmt.Sprintf("%d (%d)", r.Instances, r.PeakInstances) })
		row("GPU-seconds paid", func(r *Result) string { return fmt.Sprintf("%.0f", r.PaidGPUSeconds) })
		row("Useful share of paid GPU time", func(r *Result) string { return fmt.Sprintf("%.0f%%", 100*r.Utilization) })
		row("GPU-seconds held by partly started gangs", func(r *Result) string { return fmt.Sprintf("%.0f", r.StrandedGPUSeconds) })
		row("GPU-seconds of gangs running across fabrics", func(r *Result) string { return fmt.Sprintf("%.0f", r.SplitGPUSeconds) })
		row("Create calls (ICE / quota rejections)", func(r *Result) string {
			return fmt.Sprintf("%d (%d / %d)", r.CreateCalls, r.ICERejections, r.QuotaRejections)
		})
		row("Leaked instances / duplicate claims", func(r *Result) string {
			return fmt.Sprintf("%d / %d", r.LeakedInstances, r.DuplicateClaims)
		})
		row("Scale-in after the last job", func(r *Result) string { return fmt.Sprintf("%.1f s to %d servers", r.ScaleInSeconds, r.FinalInstances) })
		if name == "upgrade" {
			row("Rollout (image change to no old node)", func(r *Result) string { return fmt.Sprintf("%.1f s", r.RolloutSeconds) })
			row("PDB violations (samples)", func(r *Result) string { return fmt.Sprint(r.PDBViolations) })
			row("Evictions", func(r *Result) string { return fmt.Sprint(r.Evictions) })
			row("Most servers at once", func(r *Result) string { return fmt.Sprint(r.MaxNodes) })
		}
		row("API requests (writes)", func(r *Result) string { return fmt.Sprintf("%d (%d)", r.APIRequests, r.APIWrites) })
		for _, r := range rs {
			if len(r.Incomplete) > 0 {
				fmt.Fprintf(&b, "\n%s: unfinished jobs: %s.\n", r.Mode, strings.Join(r.Incomplete, ", "))
			}
			if len(r.Events) > 0 && name != "burst" {
				fmt.Fprintf(&b, "\n<details><summary>%s timeline</summary>\n\n```\n%s\n```\n</details>\n", r.Mode, strings.Join(r.Events, "\n"))
			}
		}
		b.WriteString("\n")
	}
	return b.String()
}

func modes(rs []*Result) []string {
	out := make([]string, len(rs))
	for i, r := range rs {
		if r.Mode == Naive {
			out[i] = "naive baseline"
		} else {
			out[i] = "this provisioner"
		}
	}
	return out
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
